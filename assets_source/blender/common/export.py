"""Exports Blender meshes as Wavefront OBJ/MTL for Forge's `forge:obj` model loader, plus the
model JSON that references them. Coordinates are converted back from Blender space to Minecraft
block space (0..1 per block) with the exact inverse of geometry.mc_to_bl."""
import json
import os

import bmesh

from . import textures

DISPLAY = {
    "gui": {"rotation": [30, 225, 0], "translation": [0, 0, 0], "scale": [0.625, 0.625, 0.625]},
    "ground": {"rotation": [0, 0, 0], "translation": [0, 3, 0], "scale": [0.25, 0.25, 0.25]},
    "fixed": {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [0.5, 0.5, 0.5]},
    "thirdperson_righthand": {"rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.375, 0.375, 0.375]},
    "firstperson_righthand": {"rotation": [0, 45, 0], "translation": [0, 0, 0], "scale": [0.40, 0.40, 0.40]},
    "firstperson_lefthand": {"rotation": [0, 225, 0], "translation": [0, 0, 0], "scale": [0.40, 0.40, 0.40]},
}


def bl_to_mc(v):
    return (v[0] + 0.5, v[2], 0.5 - v[1])


def write_obj(objects, obj_path, mtl_name):
    """Writes one OBJ containing all given objects. Returns stats (verts, faces, bounds)."""
    lines = ["# Generated by assets_source/blender (Scientia). Do not edit by hand.", f"mtllib {mtl_name}"]
    vmap, tmap, nmap = {}, {}, {}
    vs, ts, ns, faces = [], [], [], []
    mn, mx = [1e9] * 3, [-1e9] * 3
    for obj in objects:
        bm = bmesh.new()
        bm.from_mesh(obj.data)
        bm.transform(obj.matrix_world)
        ngons = [f for f in bm.faces if len(f.verts) > 4]
        if ngons:
            bmesh.ops.triangulate(bm, faces=ngons)
        bm.normal_update()
        uvl = bm.loops.layers.uv.active
        for f in bm.faces:
            idx = []
            n = bl_to_mc_dir(f.normal)
            nk = tuple(round(c, 5) for c in n)
            if nk not in nmap:
                nmap[nk] = len(ns) + 1
                ns.append(nk)
            for l in f.loops:
                p = bl_to_mc(l.vert.co)
                pk = tuple(round(c, 6) for c in p)
                for i in range(3):
                    mn[i] = min(mn[i], pk[i])
                    mx[i] = max(mx[i], pk[i])
                if pk not in vmap:
                    vmap[pk] = len(vs) + 1
                    vs.append(pk)
                uv = l[uvl].uv if uvl else (0, 0)
                tk = (round(uv[0], 6), round(uv[1], 6))
                if tk not in tmap:
                    tmap[tk] = len(ts) + 1
                    ts.append(tk)
                idx.append(f"{vmap[pk]}/{tmap[tk]}/{nmap[nk]}")
            faces.append("f " + " ".join(idx))
        bm.free()
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in vs]
    lines += [f"vt {u:.6f} {v:.6f}" for u, v in ts]
    lines += [f"vn {x:.5f} {y:.5f} {z:.5f}" for x, y, z in ns]
    lines.append("usemtl atlas")
    lines += faces
    with open(obj_path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return {"vertices": len(vs), "faces": len(faces), "min": mn, "max": mx}


def bl_to_mc_dir(n):
    return (n[0], n[2], -n[1])


def write_mtl(path):
    with open(path, "w", newline="\n") as fh:
        fh.write("# Generated by assets_source/blender (Scientia)\nnewmtl atlas\nKd 1.0 1.0 1.0\nd 1.0\nmap_Kd #atlas\n")


def write_model_json(path, obj_resource, translucent):
    data = {
        "loader": "forge:obj",
        "model": obj_resource,
        "flip_v": True,
        "emissive_ambient": True,
        "automatic_culling": False,
        "shade_quads": True,
        "render_type": "minecraft:translucent" if translucent else "minecraft:cutout",
        "textures": {"atlas": "scientia:block/lab_atlas", "particle": "scientia:block/steel"},
        "display": DISPLAY,
    }
    with open(path, "w", newline="\n") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")


def export_model(name, objects, models_dir):
    """Exports `objects` as models/block/<name>.obj/.mtl/.json. Returns stats."""
    os.makedirs(models_dir, exist_ok=True)
    obj_file = os.path.join(models_dir, name + ".obj")
    mtl_file = os.path.join(models_dir, name + ".mtl")
    stats = write_obj(objects, obj_file, name + ".mtl")
    write_mtl(mtl_file)
    tiles = set()
    for o in objects:
        tiles.update(o["tiles"])
    translucent = bool(tiles & textures.TRANSLUCENT)
    write_model_json(os.path.join(models_dir, name + ".json"), f"scientia:models/block/{name}.obj", translucent)
    stats["translucent"] = translucent
    stats["tiles"] = sorted(tiles)
    return stats
